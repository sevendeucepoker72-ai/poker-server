// OFFLINE generator for src/ai/studDrawCdf.ts (stud-draw-lowball, bots review 2026-11-04): the first-round
// heads-up equity quantiles q[0..100] per game that equityToPercentile maps a bot's first-round equity through.
// Deterministic: a seeded LCG picks the spots, and each equity is seeded from its own spot. No per-boot table.
// Usage (repo root): npx ts-node --transpile-only bake-stud-draw-cdf.ts   (about 1.5-3 min)
// The file is written only after every equity is computed (studDrawStrength imports the current one meanwhile).
import fs from 'fs';
import path from 'path';
import { Card } from './src/game/Card';
import { StudDrawKind, isStudKind, firstRoundEquity, drawsLeftAt } from './src/ai/studDrawStrength';

const SEED = 20261104;
const N = 4000;
const KINDS: StudDrawKind[] = ['stud-hi', 'stud8', 'razz', 'draw-hi', 'deuce7', 'badugi'];
const deck: Card[] = [];
for (let s = 0; s < 4; s++) for (let r = 2; r <= 14; r++) deck.push({ rank: r, suit: s } as Card);
let seed = SEED;
const rnd = (): number => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296);
function deal(n: number): Card[] {
  const d = deck.slice();
  for (let i = 0; i < n; i++) { const j = i + Math.floor(rnd() * (d.length - i)); [d[i], d[j]] = [d[j], d[i]]; }
  return d.slice(0, n);
}
const lines: string[] = [];
for (const kind of KINDS) {
  const stud = isStudKind(kind);
  const eqs: number[] = [];
  for (let i = 0; i < N; i++) {
    const c = deal(stud ? 7 : kind === 'badugi' ? 4 : 5);
    // Stud: the 3 cards + 4 other door cards showing (5-handed); draw games: the dealt hand, nothing visible.
    const mine = stud ? c.slice(0, 3) : c;
    const dead = stud ? c.slice(3, 7) : [];
    eqs.push(firstRoundEquity(kind, mine, dead, drawsLeftAt(kind, 'PreFlop'), 0));   // budget 0 = no deadline
  }
  eqs.sort((a, b) => a - b);
  const q = Array.from({ length: 101 }, (_, k) => Number(eqs[Math.min(N - 1, Math.round((k / 100) * (N - 1)))].toFixed(4)));
  lines.push(`  '${kind}': [${q.join(', ')}],`);
  console.log(kind, 'q10', q[10], 'q50', q[50], 'q90', q[90]);
}
const text = [
  '// GENERATED by bake-stud-draw-cdf.ts (seed 20261104, N 4000, FIRST_ROUND_SIMS) - do not edit by hand.',
  '// Re-run `npx ts-node --transpile-only bake-stud-draw-cdf.ts` after changing FIRST_ROUND_SIMS, keepForDraw or any value function.',
  "import type { StudDrawKind } from './studDrawStrength';",
  '',
  'export const FIRST_ROUND_CDF: Record<StudDrawKind, number[]> = {',
  ...lines,
  '};',
  '',
].join('\n');   // LF only, ASCII only
fs.writeFileSync(path.join(__dirname, 'src', 'ai', 'studDrawCdf.ts'), text, 'utf8');
